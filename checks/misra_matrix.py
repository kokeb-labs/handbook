#!/usr/bin/env python3
"""Validate the MISRA C++:2023 compliance matrix and its project-wide deviations.

  check     validate compliance/misra-cpp-2023.yml and compliance/misra-cpp-2023-deviations.yml, then fail if the
            generated counts in docs/coding-standards.md or the safety-level clang-tidy profile
            (config/.clang-tidy-safety) are stale (CI runs this)
  gen       rewrite the generated counts block in docs/coding-standards.md and config/.clang-tidy-safety
  tidy      list the clang-tidy checks the matrix names: on at every level (config/.clang-tidy) or safety only
  summary   print the counts as Markdown
  selftest  break a copy of the matrix in known ways and confirm each break is reported (CI runs this)

What `check` enforces:
  - every guideline of the edition is present exactly once: the ids match the edition's count, per kind and
    category, recorded below as constants;
  - kind, category, decidability and scope are valid and consistent with the id (directives: decidable n/a);
  - the summary is our own one line of at most 12 words;
  - our_category is the same as MISRA's or stricter, never weaker;
  - an applicable guideline names at least one verification other than not-applicable; one that no tool fully
    decides names a review step and the commercial checker;
  - a guideline that does not apply gives its reason and a not-applicable verification;
  - every deviation names an existing, non-mandatory guideline, is listed on that guideline's entry (and the
    reverse), and has a scope, justification, mitigation, approver and review date.

The safety-level profile is config/.clang-tidy plus every clang-tidy check the matrix names that config/.clang-tidy
leaves off, with the stricter options those checks need for the guidelines (SAFETY_OPTIONS). It is generated, so
the two files cannot drift apart.

Usage: misra_matrix.py {check,gen,summary,tidy,selftest} [--root .]

Requires PyYAML.
"""

from __future__ import annotations

import argparse
import copy
import fnmatch
import pathlib
import re
import sys
import textwrap

import yaml

MATRIX = "compliance/misra-cpp-2023.yml"
DEVIATIONS = "compliance/misra-cpp-2023-deviations.yml"
DOC = "docs/coding-standards.md"
TIDY_CONFIG = "config/.clang-tidy"
SAFETY_CONFIG = "config/.clang-tidy-safety"
# Options the safety profile sets on top of config/.clang-tidy, for the guideline named.
SAFETY_OPTIONS = {
    "hicpp-multiway-paths-covered.WarnOnMissingElse": True,  # Rule 9.4.1: an if / else-if chain ends with else
}
BEGIN = "<!-- misra-counts:begin (generated by checks/misra_matrix.py gen) -->"
END = "<!-- misra-counts:end -->"

# MISRA C++:2023 (TC1:2026 adds no guidelines): 179 guidelines, 4 directives and 175 rules.
TOTAL = 179
EXPECTED = {
    ("directive", "required"): 2,
    ("directive", "advisory"): 2,
    ("rule", "mandatory"): 5,
    ("rule", "required"): 122,
    ("rule", "advisory"): 48,
}
RANK = {"advisory": 0, "required": 1, "mandatory": 2}
TOOLS = ("compiler", "clang-tidy", "cppcheck", "codeql", "handbook-check")
METHODS = TOOLS + ("review", "commercial-checker", "not-applicable")
KEYS = {"id", "kind", "category", "decidable", "scope", "summary", "applies", "reason", "our_category",
        "verification", "deviations", "note"}
DEV_KEYS = {"id", "guideline", "scope", "justification", "mitigation", "approved_by", "date", "review_by"}
ID_RE = re.compile(r"^(Rule|Dir) (\d+)\.(\d+)\.(\d+)$")
DEV_RE = re.compile(r"^MD-CPP-\d{3}$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
SUMMARY_WORDS = 12


def yes(v) -> str | None:
    """YAML 1.1 reads yes/no as booleans; accept both spellings."""
    if v is True or v == "yes":
        return "yes"
    if v is False or v == "no":
        return "no"
    return None if v is None else str(v)


def sort_key(gid: str):
    m = ID_RE.match(gid)
    return tuple(int(x) for x in m.groups()[1:]) if m else (999,)


def decided(entry: dict) -> list[str]:
    """The tools that fully decide a guideline (a tool entry without `partial: true`)."""
    return [v["by"] for v in entry.get("verification") or []
            if isinstance(v, dict) and v.get("by") in TOOLS and not v.get("partial")]


def validate(matrix: dict, deviations: dict) -> list[str]:
    errors: list[str] = []

    def err(where: str, msg: str) -> None:
        errors.append(f"{where}: {msg}")

    entries = matrix.get("guidelines")
    if not isinstance(entries, list):
        return [f"{MATRIX}: needs a `guidelines` list"]
    for key in ("edition", "corrigendum", "licensed_copy_sha256"):
        if not matrix.get(key):
            err(MATRIX, f"missing `{key}`")
    if not re.fullmatch(r"[0-9a-f]{64}", str(matrix.get("licensed_copy_sha256", ""))):
        err(MATRIX, "licensed_copy_sha256 must be a SHA-256 in lower-case hex")

    seen: dict[str, dict] = {}
    counts: dict[tuple[str, str], int] = {}
    for i, e in enumerate(entries):
        if not isinstance(e, dict):
            err(f"{MATRIX} entry {i + 1}", "not a mapping")
            continue
        gid = str(e.get("id", ""))
        where = f"{MATRIX} {gid or f'entry {i + 1}'}"
        m = ID_RE.match(gid)
        if not m:
            err(where, "id must look like `Rule 7.0.5` or `Dir 0.3.1`")
            continue
        if gid in seen:
            err(where, "listed more than once")
        seen[gid] = e
        extra = set(e) - KEYS
        if extra:
            err(where, f"unknown keys {sorted(extra)}")
        kind = e.get("kind")
        want_kind = "directive" if m.group(1) == "Dir" else "rule"
        if kind != want_kind:
            err(where, f"kind must be {want_kind}")
        cat = e.get("category")
        if cat not in RANK:
            err(where, f"category must be one of {sorted(RANK)}")
        else:
            counts[(want_kind, cat)] = counts.get((want_kind, cat), 0) + 1
        dec = yes(e.get("decidable"))
        if want_kind == "directive" and dec != "n/a":
            err(where, "a directive's decidable is n/a")
        if want_kind == "rule" and dec not in ("yes", "no"):
            err(where, "a rule's decidable is yes or no")
        if e.get("scope") not in ("tu", "system"):
            err(where, "scope must be tu or system")
        if want_kind == "directive" and e.get("scope") != "system":
            err(where, "a directive's scope is system")
        summary = str(e.get("summary") or "").strip()
        if not summary:
            err(where, "needs a summary in our own words")
        elif len(summary.split()) > SUMMARY_WORDS:
            err(where, f"summary over {SUMMARY_WORDS} words")
        ours = e.get("our_category")
        if ours not in RANK:
            err(where, f"our_category must be one of {sorted(RANK)} (never disapplied)")
        elif cat in RANK and RANK[ours] < RANK[cat]:
            err(where, f"our_category {ours} is weaker than MISRA's {cat}")

        ver = e.get("verification")
        if not isinstance(ver, list) or not ver:
            err(where, "needs a verification list")
            ver = []
        bys = []
        for v in ver:
            if not isinstance(v, dict) or set(v) - {"by", "how", "partial"} or v.get("by") not in METHODS:
                err(where, f"each verification is {{by: {'|'.join(METHODS)}, how: ...[, partial: true]}}")
                continue
            if not str(v.get("how") or "").strip():
                err(where, f"verification by {v['by']} needs `how`")
            if v.get("partial") and v["by"] not in TOOLS:
                err(where, "only a tool can be partial")
            bys.append(v["by"])
        applies = yes(e.get("applies"))
        if applies == "yes":
            if not [b for b in bys if b != "not-applicable"]:
                err(where, "an applicable guideline needs at least one verification")
            if "not-applicable" in bys:
                err(where, "an applicable guideline has no not-applicable verification")
            if not decided(e) and not {"review", "commercial-checker"} <= set(bys):
                err(where, "no tool fully decides it, so it needs a review step and the commercial checker")
        elif applies == "no":
            if not str(e.get("reason") or "").strip():
                err(where, "a guideline that does not apply states the reason")
            if "not-applicable" not in bys:
                err(where, "a guideline that does not apply has a not-applicable verification")
        else:
            err(where, "applies must be yes or no")
        if applies == "yes" and e.get("reason"):
            err(where, "`reason` is only for a guideline that does not apply")

    if len(seen) != TOTAL:
        err(MATRIX, f"{len(seen)} guidelines; the edition has {TOTAL}")
    for key, n in EXPECTED.items():
        if counts.get(key, 0) != n:
            err(MATRIX, f"{counts.get(key, 0)} {key[1]} {key[0]}s; the edition has {n}")
    ids = [str(e.get("id")) for e in entries if isinstance(e, dict)]
    if ids != sorted(ids, key=sort_key):
        err(MATRIX, "guidelines are listed in number order")

    devs = deviations.get("deviations")
    if not isinstance(devs, list):
        return errors + [f"{DEVIATIONS}: needs a `deviations` list"]
    dev_ids: dict[str, str] = {}
    for i, d in enumerate(devs):
        if not isinstance(d, dict):
            err(f"{DEVIATIONS} entry {i + 1}", "not a mapping")
            continue
        did = str(d.get("id", ""))
        where = f"{DEVIATIONS} {did or f'entry {i + 1}'}"
        if not DEV_RE.match(did):
            err(where, "id must look like MD-CPP-001")
        if did in dev_ids:
            err(where, "duplicate id")
        missing = sorted(k for k in DEV_KEYS if not str(d.get(k) or "").strip())
        if missing:
            err(where, f"missing {missing}")
        extra = set(d) - DEV_KEYS
        if extra:
            err(where, f"unknown keys {sorted(extra)}")
        for k in ("date", "review_by"):
            if d.get(k) is not None and not DATE_RE.match(str(d[k])):
                err(where, f"{k} must be YYYY-MM-DD")
        if d.get("date") and d.get("review_by") and str(d["review_by"]) <= str(d["date"]):
            err(where, "review_by is after date")
        gid = str(d.get("guideline", ""))
        dev_ids[did] = gid
        g = seen.get(gid)
        if g is None:
            err(where, f"guideline {gid!r} is not in the matrix")
            continue
        if g.get("category") == "mandatory" or g.get("our_category") == "mandatory":
            err(where, f"{gid} is mandatory: MISRA allows no deviation from it")
        if did not in (g.get("deviations") or []):
            err(where, f"{gid}'s matrix entry does not list {did} under `deviations`")
    for gid, g in seen.items():
        for did in g.get("deviations") or []:
            if dev_ids.get(did) != gid:
                err(f"{MATRIX} {gid}", f"lists deviation {did}, which is not a record for this guideline")
    return errors


def summary(matrix: dict, deviations: dict) -> str:
    entries = matrix["guidelines"]
    by_cat = {c: [0, 0] for c in ("mandatory", "required", "advisory")}
    ours = {c: 0 for c in by_cat}
    for e in entries:
        by_cat[e["category"]][0 if e["kind"] == "directive" else 1] += 1
        ours[e["our_category"]] += 1
    applicable = [e for e in entries if yes(e["applies"]) == "yes"]
    tool = [e for e in applicable if decided(e)]
    partial = [e for e in applicable if not decided(e) and any(v["by"] in TOOLS for v in e["verification"])]
    review = [e for e in applicable if not any(v["by"] in TOOLS for v in e["verification"])]
    per_tool = {t: sum(1 for e in applicable if t in decided(e)) for t in TOOLS}
    raised = [e["id"] for e in entries if e["our_category"] != e["category"]]
    devs = deviations.get("deviations") or []
    lines = [
        BEGIN,
        "",
        f"MISRA C++:2023 with TC1:2026 has **{len(entries)} guidelines**: "
        f"{sum(v[0] for v in by_cat.values())} directives and {sum(v[1] for v in by_cat.values())} rules.",
        "",
        "| MISRA category | Directives | Rules | Total | Our category |",
        "| --- | --- | --- | --- | --- |",
        *(f"| {c} | {d} | {r} | {d + r} | {ours[c]} |" for c, (d, r) in by_cat.items()),
        f"| **all** | {sum(v[0] for v in by_cat.values())} | {sum(v[1] for v in by_cat.values())} | "
        f"{len(entries)} | {len(entries)} |",
        "",
        "| How it is verified | Guidelines |",
        "| --- | --- |",
        f"| Decided by an open tool (compiler, clang-tidy, cppcheck, handbook check) | {len(tool)} |",
        *(f"| &nbsp;&nbsp;of which by {t} | {per_tool[t]} |" for t in TOOLS if per_tool[t]),
        f"| Review and commercial checker, helped by a partial tool | {len(partial)} |",
        f"| Review and commercial checker only | {len(review)} |",
        f"| Not applicable to our code | {len(entries) - len(applicable)} |",
        "",
        *textwrap.wrap(
            f"A guideline can be decided by more than one tool. Raised above MISRA's category: {len(raised)} "
            f"({', '.join(raised)}). Project-wide deviations: {len(devs)} ("
            + ", ".join(str(d["id"]) + " " + str(d["guideline"]) for d in devs) + ").",
            120, break_long_words=False, break_on_hyphens=False),
        "",
        END,
    ]
    return "\n".join(lines) + "\n"


def tidy_globs(config: dict) -> list[str]:
    return [g.strip() for g in str(config.get("Checks", "")).split(",") if g.strip()]


def tidy_wanted(matrix: dict) -> set[str]:
    """Every clang-tidy check a verification of the matrix names."""
    wanted = set()
    for e in matrix["guidelines"]:
        for v in e["verification"]:
            if v["by"] == "clang-tidy":
                wanted |= set(re.findall(r"\b((?:bugprone|cert|clang-analyzer|cppcoreguidelines|fuchsia|google|hicpp|"
                                         r"misc|modernize|performance|portability|readability|concurrency|llvm)-"
                                         r"[\w.\-]*\w)", v["how"]))
    return {w for w in wanted if "*" not in w and not w.endswith(".")}


def tidy_enabled(root: pathlib.Path, matrix: dict) -> list[str]:
    """clang-tidy checks the matrix relies on that config/.clang-tidy does not enable: the safety level enables
    them through config/.clang-tidy-safety."""
    path = root / TIDY_CONFIG
    if not path.exists():
        return []
    globs = tidy_globs(yaml.safe_load(path.read_text(encoding="utf-8")) or {})

    def on(name: str) -> bool:
        state = False
        for g in globs:
            neg = g.startswith("-")
            if fnmatch.fnmatch(name, g.lstrip("-")):
                state = not neg
        return state

    return sorted(n for n in tidy_wanted(matrix) if not on(n))


def scalar(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, list):
        return "[" + ", ".join(scalar(x) for x in v) + "]"
    return "'" + str(v).replace("'", "''") + "'"


def safety_config(root: pathlib.Path, matrix: dict) -> str | None:
    """config/.clang-tidy-safety: config/.clang-tidy with every check the matrix names switched on."""
    path = root / TIDY_CONFIG
    if not path.exists():
        return None
    base = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    extra = tidy_enabled(root, matrix)
    options = [dict(o) for o in base.get("CheckOptions") or []]
    keys = {o["key"] for o in options}
    for key, value in SAFETY_OPTIONS.items():
        if key in keys:
            options = [dict(o, value=value) if o["key"] == key else o for o in options]
        else:
            options.append({"key": key, "value": value})
    out = [
        "---",
        f"# The safety-level clang-tidy profile: generated by checks/misra_matrix.py gen from {TIDY_CONFIG} and the",
        "# MISRA C++:2023 matrix (compliance/misra-cpp-2023.yml). Do not edit: change those, then run `gen`.",
        f"# It is {TIDY_CONFIG} plus the {len(extra)} checks the matrix names that the default leaves off, and the",
        "# stricter options in SAFETY_OPTIONS. A repository at the safety level points clang-tidy at this file.",
        "Checks: >-",
        ",\n".join("  " + g for g in tidy_globs(base) + extra),
        "",
    ]
    for key in ("WarningsAsErrors", "HeaderFileExtensions", "HeaderFilterRegex", "ExcludeHeaderFilterRegex",
                "FormatStyle"):
        if key in base:
            out.append(f"{key}: {scalar(base[key])}")
    out += ["", "CheckOptions:"]
    out += [f"  - {{ key: {o['key']}, value: {scalar(o['value'])} }}" for o in options]
    return "\n".join(out) + "\n"


def load(root: pathlib.Path) -> tuple[dict, dict]:
    def one(rel):
        return yaml.safe_load((root / rel).read_text(encoding="utf-8")) or {}
    return one(MATRIX), one(DEVIATIONS)


def doc_with(text: str, block: str) -> str | None:
    if BEGIN not in text or END not in text:
        return None
    head, rest = text.split(BEGIN, 1)
    return head + block.rstrip("\n") + rest.split(END, 1)[1]


def selftest(matrix: dict, deviations: dict) -> list[str]:
    """Each break must be reported; returns the breaks that were not."""
    def first(gid):
        return next(i for i, e in enumerate(matrix["guidelines"]) if e["id"] == gid)

    def mutate(fn):
        m, d = copy.deepcopy(matrix), copy.deepcopy(deviations)
        fn(m, d)
        return validate(m, d)

    cases = {
        "a missing guideline": lambda m, d: m["guidelines"].pop(first("Rule 7.0.5")),
        "a duplicate guideline": lambda m, d: m["guidelines"].insert(1, copy.deepcopy(m["guidelines"][0])),
        "a weaker category": lambda m, d: m["guidelines"][first("Rule 7.0.5")].update(our_category="advisory"),
        "a wrong MISRA category": lambda m, d: m["guidelines"][first("Rule 6.8.2")].update(category="required"),
        "no verification": lambda m, d: m["guidelines"][first("Rule 9.3.1")].update(verification=[]),
        "undecided without review": lambda m, d: m["guidelines"][first("Rule 7.0.5")].update(
            verification=[{"by": "cppcheck", "how": "signConversion", "partial": True}]),
        "not applicable without reason": lambda m, d: m["guidelines"][first("Rule 18.1.1")].pop("reason"),
        "a long summary": lambda m, d: m["guidelines"][0].update(summary=" ".join(["word"] * 13)),
        "a directive with decidability": lambda m, d: m["guidelines"][first("Dir 0.3.1")].update(decidable="yes"),
        "a deviation of a mandatory guideline": lambda m, d: d["deviations"].append(
            dict(d["deviations"][0], id="MD-CPP-999", guideline="Rule 6.8.2")),
        "a deviation of an unknown guideline": lambda m, d: d["deviations"].append(
            dict(d["deviations"][0], id="MD-CPP-998", guideline="Rule 99.9.9")),
        "a deviation the matrix does not cite": lambda m, d: m["guidelines"][first("Rule 4.1.1")].pop("deviations"),
    }
    return [name for name, fn in cases.items() if not mutate(fn)]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["check", "gen", "summary", "tidy", "selftest"])
    ap.add_argument("--root", default=".")
    a = ap.parse_args()
    root = pathlib.Path(a.root).resolve()
    try:
        matrix, deviations = load(root)
    except (OSError, yaml.YAMLError) as e:
        print(f"::error::{e}")
        return 1
    errors = validate(matrix, deviations)
    for e in errors:
        print(f"::error::{e}")
    if errors:
        print(f"{len(errors)} error(s)")
        return 1
    block = summary(matrix, deviations)
    if a.cmd == "summary":
        print(block, end="")
        return 0
    if a.cmd == "tidy":
        off = set(tidy_enabled(root, matrix))
        wanted = sorted(tidy_wanted(matrix))
        print(f"{len(wanted)} clang-tidy checks named by the matrix")
        print(f"on at every level ({TIDY_CONFIG}):", ", ".join(w for w in wanted if w not in off))
        print(f"safety level only ({SAFETY_CONFIG}):", ", ".join(w for w in wanted if w in off))
        return 0
    if a.cmd == "selftest":
        missed = selftest(matrix, deviations)
        for name in missed:
            print(f"::error::selftest: {name} was not reported")
        if missed:
            return 1
        print("selftest: every seeded break was reported")
        return 0
    doc = root / DOC
    text = doc.read_text(encoding="utf-8")
    new = doc_with(text, block)
    if new is None:
        print(f"::error file={DOC}::the generated MISRA counts block (markers) is missing")
        return 1
    safety = safety_config(root, matrix)
    safety_path = root / SAFETY_CONFIG
    if a.cmd == "gen":
        if new != text:
            doc.write_text(new, encoding="utf-8")
            print(f"wrote {DOC}")
        if safety is not None and (not safety_path.exists() or safety_path.read_text(encoding="utf-8") != safety):
            safety_path.write_text(safety, encoding="utf-8")
            print(f"wrote {SAFETY_CONFIG}")
        return 0
    if new != text:
        print(f"::error file={DOC}::MISRA counts are stale: run `python checks/misra_matrix.py gen`")
        return 1
    if safety is not None and (not safety_path.exists() or safety_path.read_text(encoding="utf-8") != safety):
        print(f"::error file={SAFETY_CONFIG}::the safety clang-tidy profile is stale: run "
              "`python checks/misra_matrix.py gen`")
        return 1
    off = tidy_enabled(root, matrix)
    if off:
        print(f"::notice::{len(off)} clang-tidy checks named by the MISRA matrix are on at the safety level only "
              f"({SAFETY_CONFIG}): {', '.join(off)}")
    print(f"{len(matrix['guidelines'])} guidelines and {len(deviations['deviations'])} deviations valid; "
          "counts current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
