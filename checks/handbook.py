#!/usr/bin/env python3
"""The Kokeb Labs handbook as data: validate the rules, generate their pages, report coverage.

Every rule lives in rules/<area>.yml. This tool makes sure the set holds together, and writes the pages that show
it, so the prose and the data can never disagree:

  validate   every rule is well formed; IDs are unique and never reused; an active `must` rule names how it is
             verified; every check it names exists in checks/registry.yml; every reference (ADR, page, standard)
             resolves
  gen        write docs/rules/<area>.md (one section per rule, anchored by its ID) and docs/rules/coverage.md
  check      validate, then fail if the generated pages are stale (CI runs this)
  export     write rules, profiles and checks as one JSON document (for ru-handbook-check and other tools)

Usage: handbook.py {validate,gen,check,export} [--root .] [--rules rules] [--out FILE]

--rules names another folder of rule files to validate against the same registry and profiles, e.g. a product
family's supplement (hf-supplement); `gen` and `check` only apply to the handbook's own rules/.

Requires PyYAML (the MkDocs toolchain has it).
"""

from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import re
import sys
import textwrap

import yaml

LEVELS = ("must", "should", "guide")
ASSURANCE = ("standard", "high", "safety")  # each level includes the ones before it
STATUSES = ("proposed", "active", "retired")
RULE_KEYS = {"id", "title", "statement", "level", "status", "applies", "verify", "rationale", "refs", "page",
             "since", "enforce_from", "origin", "notes", "replaced_by"}
STANDARDS = {
    "MISRA-CPP-2023": "MISRA C++:2023",
    "MISRA-C-2025": "MISRA C:2025",
    "CERT-CPP": "SEI CERT C++",
    "CERT-C": "SEI CERT C",
    "CPPCG": "C++ Core Guidelines",
    "IEC-62304": "IEC 62304:2006+A1:2015",
    "IEC-61508-3": "IEC 61508-3:2010",
    "ISO-26262-6": "ISO 26262-6:2018",
    "NASA-P10": "NASA/JPL Power of Ten",
}
ID_RE = re.compile(r"^(KB|HF)-([A-Z]{2,5})-(\d{3})$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
GENERATED = "<!-- generated by checks/handbook.py from rules/*.yml: edit those, then run `python checks/handbook.py gen` -->\n"
STATES = ("checked", "planned", "review", "none")
WIDTH = 120  # the org markdownlint line length


_KEEP = re.compile(r"(`[^`]*`|\]\([^)]*\)|https?://\S+)")


def md(text: str) -> str:
    """Escape what Markdown would misread in rule text written as plain words: `_` and `*` (emphasis) and `<`/`>`
    (an HTML tag, which hides `<chip>`). Code spans, link targets and bare URLs are left alone."""
    parts = _KEEP.split(str(text))
    for i in range(0, len(parts), 2):
        parts[i] = (parts[i].replace("_", "\\_").replace("*", "\\*")
                    .replace("<", "&lt;").replace(">", "&gt;"))
    return "".join(parts)


def para(text: str) -> str:
    """One paragraph wrapped at WIDTH (markdownlint MD013), never breaking a word, link or code span."""
    return textwrap.fill(" ".join(text.split()), WIDTH, break_long_words=False, break_on_hyphens=False)


def bullet(text: str) -> str:
    return textwrap.fill(" ".join(text.split()), WIDTH, initial_indent="- ", subsequent_indent="  ",
                         break_long_words=False, break_on_hyphens=False)


class Book:
    def __init__(self, root: pathlib.Path, rules_dir: str = "rules"):
        self.root = root
        self.errors: list[str] = []
        self.unused: list[str] = []
        self.profiles = self._load("profiles/profiles.yml") or {}
        registry = self._load("checks/registry.yml") or {}
        self.checks = {c["id"]: c for c in registry.get("checks", [])}
        self.areas: list[dict] = []
        for p in sorted((root / rules_dir).glob("*.yml")):
            doc = self._load(str(p.relative_to(root))) or {}
            doc["_file"] = str(p.relative_to(root))
            self.areas.append(doc)
        # IDs of rules deleted outright (rather than kept as `status: retired`): never handed out again.
        retired = root / "checks/retired-ids.yml"
        self.retired_ids = set((self._load("checks/retired-ids.yml") or {}).get("ids") or []) if retired.exists() \
            else set()

    def _load(self, rel: str):
        try:
            return yaml.safe_load((self.root / rel).read_text(encoding="utf-8"))
        except FileNotFoundError:
            self.errors.append(f"{rel}: missing")
        except yaml.YAMLError as e:
            self.errors.append(f"{rel}: not valid YAML: {e}")
        return None

    def err(self, where: str, msg: str) -> None:
        self.errors.append(f"{where}: {msg}")

    def check_for(self, cid: str) -> dict | None:
        """The registry entry for a check id; `family/param` resolves to a parametric family (clang-tidy/...)."""
        if cid in self.checks:
            return self.checks[cid]
        c = self.checks.get(cid.split("/", 1)[0])
        return c if c and c.get("parametric") and "/" in cid else None

    def rules(self):
        for area in self.areas:
            for r in area.get("rules") or []:
                yield area, r

    # -- validation ------------------------------------------------------------------------------------------------
    def validate(self) -> list[str]:
        kinds = set(self.profiles.get("kinds") or {})
        if not kinds:
            self.err("profiles/profiles.yml", "no `kinds`")
        for cid, c in self.checks.items():
            if c.get("status") not in ("implemented", "planned"):
                self.err("checks/registry.yml", f"{cid}: status must be implemented or planned")
            if c.get("status") == "implemented" and not c.get("where"):
                self.err("checks/registry.yml", f"{cid}: an implemented check says `where` it runs")
            if not c.get("summary"):
                self.err("checks/registry.yml", f"{cid}: needs a summary")
        seen: dict[str, str] = {}
        used: set[str] = set()
        for area in self.areas:
            f = area["_file"]
            prefix = area.get("prefix")
            if not (prefix and area.get("area") and area.get("title") and isinstance(area.get("rules"), list)):
                self.err(f, "needs `area`, `prefix`, `title` and a `rules` list")
                continue
            for i, r in enumerate(area["rules"]):
                if not isinstance(r, dict):
                    self.err(f"{f} rule {i + 1}", "not a mapping")
                    continue
                rid = str(r.get("id", ""))
                where = f"{f} {rid or f'rule {i + 1}'}"
                extra = set(r) - RULE_KEYS
                if extra:
                    self.err(where, f"unknown keys {sorted(extra)}")
                m = ID_RE.match(rid)
                if not m:
                    self.err(where, "id must look like KB-CPP-001 (HF-... in the HardFOC supplement)")
                elif f"{m.group(1)}-{m.group(2)}" != prefix:
                    self.err(where, f"id prefix differs from the file's prefix {prefix}")
                if rid in seen:
                    self.err(where, f"duplicate id (also in {seen[rid]})")
                seen[rid] = f
                if rid in self.retired_ids:
                    self.err(where, "this id was retired and may not be reused")
                for key in ("title", "statement", "level", "status", "applies", "since"):
                    if key not in r:
                        self.err(where, f"missing `{key}`")
                if len(str(r.get("title", ""))) > 90:
                    self.err(where, "title over 90 characters")
                elif len(f"## {rid}: {md(r.get('title', ''))} {{ #{rid.lower()} }}") > WIDTH:
                    self.err(where, "title too long once rendered as a heading; put identifiers in `code`")
                if r.get("level") not in LEVELS:
                    self.err(where, f"level must be one of {LEVELS}")
                if r.get("status") not in STATUSES:
                    self.err(where, f"status must be one of {STATUSES}")
                if r.get("status") == "retired" and not (r.get("replaced_by") or r.get("notes")):
                    self.err(where, "a retired rule says what replaced it (`replaced_by`) or why (`notes`)")
                ap = r.get("applies") or {}
                profs = ap.get("profiles") or []
                if profs != ["all"] and (not profs or not set(profs) <= kinds):
                    self.err(where, f"applies.profiles must be [all] or a subset of {sorted(kinds)}")
                if ap.get("from_level", "standard") not in ASSURANCE:
                    self.err(where, f"applies.from_level must be one of {ASSURANCE}")
                ef = r.get("enforce_from")
                if ef is not None and not DATE_RE.match(str(ef)):
                    self.err(where, "enforce_from must be YYYY-MM-DD")
                verify = r.get("verify") or []
                if not isinstance(verify, list):
                    self.err(where, "verify must be a list")
                    verify = []
                for v in verify:
                    if not isinstance(v, dict) or len(v) != 1 or next(iter(v)) not in ("check", "review"):
                        self.err(where, "each verify entry is {check: <id>} or {review: <checklist line>}")
                        continue
                    if "check" in v:
                        used.add(str(v["check"]).split("/", 1)[0])
                        if self.check_for(str(v["check"])) is None:
                            self.err(where, f"check {v['check']!r} is not in checks/registry.yml")
                if r.get("level") == "must" and r.get("status") == "active" and not verify:
                    self.err(where, "an active `must` rule names at least one check or review")
                for ref in r.get("refs") or []:
                    if not isinstance(ref, dict) or not ref or set(ref) - {"std", "id", "adr", "note"}:
                        self.err(where, "refs entries are {std, id[, note]} or {adr: N}")
                        continue
                    if "adr" in ref:
                        if not list((self.root / "docs/adr").glob(f"{int(ref['adr']):04d}-*.md")):
                            self.err(where, f"ADR {ref['adr']} does not exist")
                    elif ref.get("std") not in STANDARDS:
                        self.err(where, f"unknown standard {ref.get('std')!r} (known: {', '.join(STANDARDS)})")
                page = r.get("page")
                if page and not (self.root / "docs" / str(page).split("#")[0]).is_file():
                    self.err(where, f"page {page} does not exist under docs/")
        self.unused = sorted(c for c in set(self.checks) - used if self.checks[c].get("status") == "implemented")
        return self.errors

    # -- generation ------------------------------------------------------------------------------------------------
    def verify_state(self, r: dict) -> str:
        states = set()
        for v in r.get("verify") or []:
            if "check" in v:
                implemented = (self.check_for(str(v["check"])) or {}).get("status") == "implemented"
                states.add("checked" if implemented else "planned")
            else:
                states.add("review")
        return next((s for s in STATES if s in states), "none")

    @staticmethod
    def applies(r: dict) -> str:
        ap = r.get("applies") or {}
        lvl = ap.get("from_level", "standard")
        return ", ".join(ap.get("profiles") or []) + ("" if lvl == "standard" else f" ({lvl} level and above)")

    def area_page(self, area: dict) -> str:
        out = [GENERATED, f"# {area['title']}\n\n"]
        if area.get("intro"):
            out.append(f"{para(md(area['intro']))}\n\n")
        out.append("| Rule | Level | Applies to | Verified |\n| --- | --- | --- | --- |\n")
        for r in area["rules"]:
            if r.get("status") != "retired":
                out.append(f"| [{r['id']}](#{r['id'].lower()}) {md(r['title'])} | {r['level']} | {self.applies(r)} | "
                           f"{self.verify_state(r)} |\n")
        for r in area["rules"]:
            out.append(f"\n## {r['id']}: {md(r['title'])} {{ #{r['id'].lower()} }}\n\n")
            if r.get("status") != "active":
                tail = f" Replaced by {r['replaced_by']}." if r.get("replaced_by") else ""
                note = textwrap.indent(para(md(f"{r.get('notes') or 'Not enforced yet.'}{tail}")), "    ")
                out.append(f"!!! note \"{r['status'].capitalize()}\"\n\n{note}\n\n")
            ef = f" · enforced from {r['enforce_from']}" if r.get("enforce_from") else ""
            out.append(para(f"**{r['level'].upper()}** · {self.applies(r)} · since {r['since']}{ef}") + "\n\n")
            out.append(f"{para(md(r['statement']))}\n\n")
            if r.get("rationale"):
                out.append(f"{para('*Why:* ' + md(r['rationale']))}\n\n")
            ver = []
            for v in r.get("verify") or []:
                if "check" in v:
                    c = self.check_for(str(v["check"])) or {}
                    ver.append(f"`{v['check']}` ({c.get('status', 'unknown')}): {md(c.get('summary', ''))}")
                else:
                    ver.append(f"review: {md(v['review'])}")
            if ver:
                out.append("*Verified by:*\n\n" + "".join(f"{bullet(v)}\n" for v in ver) + "\n")
            refs = []
            for ref in r.get("refs") or []:
                if "adr" in ref:
                    n = int(ref["adr"])
                    f = next((self.root / "docs/adr").glob(f"{n:04d}-*.md"))
                    refs.append(f"[ADR-{n:04d}](../adr/{f.name})")
                else:
                    note = f" ({ref['note']})" if ref.get("note") else ""
                    refs.append(f"{STANDARDS[ref['std']]} {ref.get('id', '')}".strip() + note)
            if refs:
                out.append(para("*See also:* " + "; ".join(refs)) + "\n\n")
            if r.get("page"):
                out.append(f"*Explained in:* [{r['page'].split('#')[0]}](../{r['page']})\n")
        return "".join(out)

    def coverage_page(self) -> str:
        rows, total = [], dict.fromkeys(STATES, 0)
        for area in self.areas:
            c = dict.fromkeys(STATES, 0)
            for r in area.get("rules") or []:
                if r.get("status") != "retired" and r.get("level") == "must":
                    c[self.verify_state(r)] += 1
            n = sum(c.values())
            for k in STATES:
                total[k] += c[k]
            pct = f"{100 * c['checked'] // n}%" if n else "-"
            rows.append(f"| [{md(area['title'])}]({pathlib.Path(area['_file']).stem}.md) | {n} | {c['checked']} | "
                        f"{c['planned']} | {c['review']} | {pct} |\n")
        n = sum(total.values())
        pct = f"{100 * total['checked'] // n}%" if n else "-"
        planned = sorted((c for c in self.checks.values() if c.get("status") == "planned"), key=lambda c: c["id"])
        return "".join([
            GENERATED, "# Coverage\n\n",
            para("How the **must** rules are verified. *Checked*: a tool verifies it in CI today. *Planned*: the rule "
                 "names a check that is not built yet. *Review*: verified in review against the pull-request "
                 "checklist.") + "\n\n",
            "| Area | Must rules | Checked | Planned | Review | Checked share |\n| --- | --- | --- | --- | --- | --- |\n",
            *rows, f"| **All** | {n} | {total['checked']} | {total['planned']} | {total['review']} | {pct} |\n\n",
            "## Checks still to build\n\n",
            *(bullet("`" + c["id"] + "`: " + md(c["summary"])) + "\n" for c in planned),
            "" if planned else "None.\n",
        ])

    def generated(self) -> dict[pathlib.Path, str]:
        out = {self.root / "docs/rules" / f"{pathlib.Path(a['_file']).stem}.md": self.area_page(a)
               for a in self.areas if a.get("rules")}
        out[self.root / "docs/rules/coverage.md"] = self.coverage_page()
        return out

    def export(self) -> dict:
        return {
            "generated": datetime.date.today().isoformat(),
            "profiles": self.profiles,
            "checks": list(self.checks.values()),
            "rules": [dict(r, area=a["area"]) for a, r in self.rules()],
        }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["validate", "gen", "check", "export"])
    ap.add_argument("--root", default=".")
    ap.add_argument("--rules", default="rules")
    ap.add_argument("--out", default="-")
    a = ap.parse_args()
    book = Book(pathlib.Path(a.root).resolve(), a.rules)
    if a.rules != "rules" and a.cmd in ("gen", "check"):
        ap.error("gen and check apply to rules/ only; use validate for a supplement")
    errors = book.validate()
    for e in errors:
        print(f"::error::{e}")
    if errors:
        print(f"{len(errors)} error(s)")
        return 1
    for cid in book.unused:
        print(f"::warning::checks/registry.yml: {cid} is implemented but no rule names it yet")
    n = sum(1 for _ in book.rules())
    if a.cmd == "validate":
        print(f"{n} rules in {len(book.areas)} areas, {len(book.checks)} checks: valid")
    elif a.cmd == "gen":
        for path, text in book.generated().items():
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                path.write_text(text, encoding="utf-8")
                print(f"wrote {path.relative_to(book.root)}")
    elif a.cmd == "check":
        stale = [p for p, t in book.generated().items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        for p in stale:
            print(f"::error file={p.relative_to(book.root)}::stale: run `python checks/handbook.py gen`")
        if stale:
            return 1
        print(f"{n} rules valid; generated pages current")
    else:
        text = json.dumps(book.export(), indent=1, default=str)
        if a.out == "-":
            print(text)
        else:
            pathlib.Path(a.out).write_text(text + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
